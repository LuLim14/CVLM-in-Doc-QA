#!/usr/bin/env python3
"""Парные разности training loss между ветками + moving-block bootstrap CI.

Именно этот скрипт породил таблицу «optimization dynamics» в статье — раньше
расчёт жил инлайном, теперь он в репозитории и воспроизводим.

ВАЖНО о том, что эти CI значат (и чего НЕ значат):
  * ветки видят ИДЕНТИЧНЫЕ батчи в идентичном порядке (проверяется по
    [batch-hash] в pipeline.log), поэтому по-шаговые разности спарены;
  * bootstrap ресэмплит блоки ВНУТРИ одной пары траекторий -> интервал
    характеризует шум траектории, а НЕ разброс между запусками/seed'ами и не
    неопределённость тренда между строками;
  * это метрика оптимизации, а не качества: основные клеймы должны опираться
    на held-out paired bootstrap (tools/bootstrap_ci.py) и несколько seed.

Запуск:
  python tools/block_bootstrap_train.py --runs_root ~/Desktop/CVLM/runs_hse \
      --pairs "randomvit-novit,vit-randomvit" \
      --stages "1:1:1500,2:1501:3000,4:3001:4500,8:4501:6000,16:6001:0"
"""

import argparse
import csv
import math
import os
import random


def load(path):
    with open(path, encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    return {int(float(r["step"])): float(r["loss"])
            for r in rows if r.get("step") and r.get("loss")}


def paired_block_bootstrap(da, db, lo, hi, tail, n_boot, block, rng):
    steps = sorted(s for s in da if lo <= s <= hi and s in db)
    if not steps:
        return None
    steps = [s for s in steps if s >= max(steps) - tail]
    if len(steps) < 10:
        return None
    d = [da[s] - db[s] for s in steps]
    n = len(d)
    mean = sum(d) / n
    block = min(max(int(block), 1), n)
    nblocks = max(math.ceil(n / block), 1)
    boots = []
    for _ in range(n_boot):
        smp = []
        for _ in range(nblocks):
            i = rng.randrange(0, n - block + 1)
            smp += d[i:i + block]
        smp = smp[:n]
        boots.append(sum(smp) / len(smp))
    boots.sort()
    lo_idx = max(min(int(0.025 * n_boot), n_boot - 1), 0)
    hi_idx = max(min(int(0.975 * n_boot), n_boot - 1), 0)
    return mean, boots[lo_idx], boots[hi_idx], n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs_root", required=True,
                    help="директория с abl_<branch>.csv (metrics.csv, скопированные с кластера)")
    ap.add_argument("--pairs", default="randomvit-novit,vit-randomvit",
                    help="через запятую: A-B, разность считается L(A) - L(B)")
    ap.add_argument("--stages", default="1:1:1500,2:1501:3000,4:3001:4500,8:4501:6000,16:6001:0",
                    help="cr:lo:hi, hi=0 означает +inf")
    ap.add_argument("--tail_steps", type=int, default=1000)
    ap.add_argument("--n_boot", type=int, default=4000)
    ap.add_argument("--block", type=int, default=5, help="в лог-точках (log_interval шагов каждая)")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--out_tex", default="")
    args = ap.parse_args()

    rng = random.Random(args.seed)
    stages = []
    for tok in args.stages.split(","):
        cr, lo, hi = tok.split(":")
        stages.append((int(cr), int(lo), int(hi) if int(hi) > 0 else 10 ** 12))
    pairs = [tuple(p.split("-")) for p in args.pairs.split(",")]

    data = {}
    for a, b in pairs:
        for br in (a, b):
            if br in data:
                continue
            f = os.path.join(args.runs_root, f"abl_{br}.csv")
            if not os.path.exists(f):
                raise SystemExit(f"нет файла {f}")
            data[br] = load(f)

    rows = []
    hdr = f"{'cr':>3}"
    for a, b in pairs:
        hdr += f" | {a+' - '+b:>34} {'PPLx':>6}"
    print(hdr)
    print("-" * len(hdr))
    for cr, lo, hi in stages:
        line = f"{cr:>3}"
        rec = {"cr": cr}
        for a, b in pairs:
            r = paired_block_bootstrap(data[a], data[b], lo, hi, args.tail_steps,
                                       args.n_boot, args.block, rng)
            if r is None:
                line += f" | {'--':>34} {'--':>6}"
                rec[f"{a}-{b}"] = None
                continue
            m, l, h, n = r
            star = "*" if (l > 0 or h < 0) else " "
            line += f" | {f'{m:+.3f} [{l:+.3f},{h:+.3f}] n={n}{star}':>34} {math.exp(m):>6.2f}"
            rec[f"{a}-{b}"] = dict(mean=m, lo=l, hi=h, n=n, ppl_ratio=math.exp(m))
        rows.append(rec)
        print(line)
    print(f"\n* = CI не накрывает 0. bootstrap: {args.n_boot} ресэмплов, блок {args.block} лог-точек, "
          f"хвост {args.tail_steps} шагов каждой стадии.")
    print("CI посчитаны ВНУТРИ одной пары траекторий: не покрывают разброс по seed и тренд между строками.")

    if args.out_tex:
        with open(args.out_tex, "w", encoding="utf-8") as f:
            f.write("% generated by tools/block_bootstrap_train.py\n")
            f.write("\\begin{tabular}{l" + "c" * len(pairs) + "}\n\\toprule\n")
            f.write("$cr$ & " + " & ".join(f"{a} $-$ {b}" for a, b in pairs) + " \\\\\n\\midrule\n")
            for rec in rows:
                cells = []
                for a, b in pairs:
                    v = rec[f"{a}-{b}"]
                    cells.append("--" if not v else
                                 f"${v['mean']:+.3f}$ [${v['lo']:+.3f}$, ${v['hi']:+.3f}$]")
                f.write(f"{rec['cr']} & " + " & ".join(cells) + " \\\\\n")
            f.write("\\bottomrule\n\\end{tabular}\n")
        print(f"LaTeX -> {args.out_tex}")


if __name__ == "__main__":
    main()
